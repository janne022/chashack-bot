const CATALOGS: Record<BotLocale, Catalog> = { en: EN, sv: SV };

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (params === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/**
 * Translate a key for the given locale. Falls back to English, then to the
 * key itself. Pure — safe to call from anywhere, including domain code.
 */
export function t(
  locale: BotLocale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = CATALOGS[locale][key] ?? CATALOGS.en[key] ?? key;
  return interpolate(raw, params);
}
